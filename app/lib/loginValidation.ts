// Одинаковые правила для самостоятельной смены логина и изменения администратором.
// Регистр сохраняется: существующий вход в проекте сравнивает логины точно.
export const getLoginValidationError = (login: string): string | null => {
    if (!login || login.length > 120 || /[\s\u0000-\u001f\u007f]/u.test(login)) {
        return 'Логин должен содержать от 1 до 120 символов без пробелов и управляющих символов';
    }

    return null;
};
